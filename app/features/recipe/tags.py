def make_slug(title: str, source: str = "manual") -> str:
    """菜谱主键：`来源:标题`（标题只做空白压缩，保留中文）。

    不做拼音/URL 转写：库是中文的，直接用中文当键在 Mongo 里查起来一目了然，
    也免了同音字撞车。同名同源视为同一道菜（重复导入时覆盖，正是想要的）。
    """
    clean = re.sub(r"\s+", "", (title or "").strip())
    clean = clean.replace("/", "-")  # 斜杠会让它看起来像路径，避免混淆
    return f"{source}:{clean}"


def _hit(keywords: Iterable[str], haystack: str) -> bool:
    return any(re.search(kw, haystack) for kw in keywords)


def _derive_method(category: str, haystack: str) -> list[str]:
    tags: list[str] = []
    cat_tag = _CATEGORY_METHOD.get(category, "")
    if cat_tag:
        tags.append(cat_tag)
    for tag, kws in _METHOD_KEYWORDS.items():
        if tag not in tags and _hit(kws, haystack):
            tags.append(tag)
    return tags


def _derive_flavor(haystack: str, title: str = "") -> list[str]:
    tags = [tag for tag, kws in _FLAVOR_KEYWORDS.items() if _hit(kws, haystack)]

    # 标题带辣字但配料没写辣椒（辣味藏在半成品浇头里）时补一刀
    if title and _TITLE_SPICY.search(title) and not any(
        t in ("麻辣", "香辣", "酸辣") for t in tags
    ):
        tags.append("麻辣" if "麻" in title else "香辣")

    # 麻辣命中时「香辣」是冗余的 —— 花椒+辣椒的组合两个都会中，只保留更具体的。
    if "麻辣" in tags and "香辣" in tags:
        tags.remove("香辣")

    # 一个口味信号都没有，才是真的清淡
    if not tags:
        tags.append("清淡")
    return tags


def _derive_ingredient(haystack: str) -> list[str]:
    tags: list[str] = []
    for tag, kws in _INGREDIENT_KEYWORDS.items():
        if _hit(kws, haystack):
            tags.append(tag)
    # 「鱼虾」的关键词含裸「鱼」，会被「鱼露」「鱼香」这类调味词误伤。
    # 鱼香肉丝里没有鱼 —— 命中的若只是调味语境就撤掉。
    if "鱼虾" in tags and not re.search(r"(?<!鱼)鱼(?!露|香)|虾", haystack):
        tags.remove("鱼虾")
    return tags


def derive_tags(
    title: str,
    category: str = "",
    ingredients: Iterable[str] = (),
    steps: Iterable[str] = (),
) -> dict[str, list[str]]:
    """从菜谱内容推导三类标签。

    Returns:
        {"method": [...], "flavor": [...], "ingredient": [...]}
    """
    haystack = "\n".join([title or "", category or "", *ingredients, *steps])
    return {
        "method": _derive_method(category, haystack),
        "flavor": _derive_flavor(haystack, title=title or ""),
        "ingredient": _derive_ingredient(haystack),
    }
